#!/usr/bin/env python3
"""Run and compare all Week 1 OR-Tools routing baselines."""

from __future__ import annotations

import json
from pathlib import Path

import matplotlib.pyplot as plt

from cvrp import solve_cvrp
from routing_data import BLOCK_LOCATIONS
from tsp import solve_tsp
from vrp import solve_vrp
from vrptw import solve_vrptw


RESULTS_DIR = Path(__file__).resolve().parents[1] / "results"


def plot_results(results: list[dict[str, object]]) -> None:
    colors = ["#0072B2", "#D55E00", "#009E73", "#CC79A7"]
    fig, axes = plt.subplots(2, 2, figsize=(13, 11), constrained_layout=True)
    for ax, result in zip(axes.flat, results):
        for route_index, route in enumerate(result["routes"]):
            points = [BLOCK_LOCATIONS[node] for node in route["nodes"]]
            xs, ys = zip(*points)
            ax.plot(
                xs,
                ys,
                marker="o",
                linewidth=2,
                color=colors[route_index % len(colors)],
                label=f"Vehicle {route['vehicle']}",
            )
        for node, (x, y) in enumerate(BLOCK_LOCATIONS):
            marker = "s" if node == 0 else "o"
            color = "black" if node == 0 else "white"
            ax.scatter(
                x,
                y,
                marker=marker,
                s=75,
                facecolor=color,
                edgecolor="black",
                zorder=5,
            )
            ax.annotate(str(node), (x, y), xytext=(5, 5), textcoords="offset points", fontsize=9)
        ax.set_title(result["problem"])
        ax.set_xlabel("x-coordinate (block units)")
        ax.set_ylabel("y-coordinate (block units)")
        ax.grid(alpha=0.25)
        ax.set_aspect("equal", adjustable="box")
        ax.legend(loc="best", fontsize=8)
    fig.suptitle("Google OR-Tools Routing Baselines", fontsize=16)
    fig.savefig(RESULTS_DIR / "baseline_routes.png", dpi=180)
    plt.close(fig)


def write_route_tables(results: list[dict[str, object]]) -> None:
    lines = [
        "# OR-Tools Baseline Route Tables",
        "",
        "Generated by `compare_or_tools_baselines.py`.",
        "",
    ]
    for result in results:
        lines.extend(
            [
                f"## {result['problem']}",
                "",
                f"- Solver objective: `{result['objective']}` ({result['objective_interpretation']})",
            ]
        )
        if "total_distance" in result:
            lines.append(f"- Total route distance: `{result['total_distance']} m`")
        if "maximum_route_distance" in result:
            lines.append(f"- Maximum route distance: `{result['maximum_route_distance']} m`")
        lines.extend(
            [
                "",
                "| Vehicle | Route | Distance / travel time | Load | Service-time ranges |",
                "|---:|---|---:|---:|---|",
            ]
        )
        for route in result["routes"]:
            route_text = " -> ".join(map(str, route["nodes"]))
            load = route.get("load", "-")
            times = route.get("cumulative_time")
            time_text = (
                "; ".join(
                    f"{node}: [{bounds[0]}, {bounds[1]}]"
                    for node, bounds in zip(route["nodes"], times)
                )
                if times
                else "-"
            )
            lines.append(
                f"| {route['vehicle']} | `{route_text}` | {route['distance']} | {load} | {time_text} |"
            )
        lines.append("")
    (RESULTS_DIR / "route_tables.md").write_text("\n".join(lines), encoding="utf-8")


def run_comparison() -> list[dict[str, object]]:
    return [solve_tsp(), solve_vrp(), solve_cvrp(), solve_vrptw()]


def main() -> None:
    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    results = run_comparison()
    (RESULTS_DIR / "baseline_results.json").write_text(
        json.dumps(results, indent=2), encoding="utf-8"
    )
    write_route_tables(results)
    plot_results(results)
    for result in results:
        print(f"{result['problem']}: objective={result['objective']}, routes={len(result['routes'])}")


if __name__ == "__main__":
    main()
